CREATE TABLE password_reset_tokens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 token_hash VARCHAR(64) NOT NULL UNIQUE,
 issued_token_version BIGINT NOT NULL CHECK (issued_token_version >= 0),
 created_at TIMESTAMP NOT NULL,
 expires_at TIMESTAMP NOT NULL,
 used_at TIMESTAMP,
 revoked BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT ck_reset_expiry CHECK (expires_at > created_at)
);
CREATE INDEX idx_reset_tokens_user ON password_reset_tokens(user_id);
CREATE INDEX idx_reset_tokens_expiry ON password_reset_tokens(expires_at);
CREATE TABLE password_reset_rate_limits (
 bucket_key VARCHAR(64) PRIMARY KEY,
 window_started_at TIMESTAMP NOT NULL,
 request_count INTEGER NOT NULL CHECK (request_count >= 0),
 last_accepted_at TIMESTAMP
);
CREATE INDEX idx_reset_rate_window ON password_reset_rate_limits(window_started_at);
