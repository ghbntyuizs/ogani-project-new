-- ---------------------------------------------------------------------
-- 1. AUTH
-- ---------------------------------------------------------------------
CREATE TABLE roles (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(30) NOT NULL UNIQUE          -- ADMIN, STAFF, CUSTOMER
);

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id       INTEGER NOT NULL,
  email         VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  first_name    VARCHAR(60)  NOT NULL,
  last_name     VARCHAR(60)  NOT NULL,
  phone         VARCHAR(20),
  avatar_url    VARCHAR(255),
  status        VARCHAR(30) NOT NULL DEFAULT 'ACTIVE' CHECK ("status" IN ('ACTIVE','BLOCKED')),
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

-- Checkout: "Billing Details" + "Ship to a different address?"
CREATE TABLE customer_addresses (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        BIGINT NOT NULL,
  recipient_name VARCHAR(120) NOT NULL,
  phone          VARCHAR(20)  NOT NULL,
  country        VARCHAR(60)  NOT NULL DEFAULT 'Vietnam',
  address_line   VARCHAR(255) NOT NULL,
  city           VARCHAR(80)  NOT NULL,              -- Town/City
  state          VARCHAR(80),                        -- Country/State
  postcode       VARCHAR(20),
  is_default     BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT fk_addr_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 2. CATALOG
-- ---------------------------------------------------------------------
-- "All departments" menu + category carousel on home page
CREATE TABLE categories (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id  INTEGER NULL,
  name       VARCHAR(100) NOT NULL,
  slug       VARCHAR(120) NOT NULL UNIQUE,
  image_url  VARCHAR(255),                           -- ảnh carousel trang chủ
  sort_order INT NOT NULL DEFAULT 0,
  is_active  BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT fk_cat_parent FOREIGN KEY (parent_id) REFERENCES categories(id) ON DELETE SET NULL
);

CREATE TABLE products (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id       INTEGER NOT NULL,
  name              VARCHAR(200) NOT NULL,
  slug              VARCHAR(220) NOT NULL UNIQUE,
  sku               VARCHAR(50)  NOT NULL UNIQUE,
  short_description VARCHAR(500),                    -- đoạn ngắn cạnh nút ADD TO CART
  description       TEXT,                            -- tab "Description"
  information       TEXT,                            -- tab "Information"
  price             DECIMAL(12,2) NOT NULL,          -- giá gốc (giá gạch ngang)
  sale_price        DECIMAL(12,2) NULL,              -- giá đang bán; NULL = không giảm giá ("Sale Off -20%")
  weight_value      DECIMAL(8,2),                    -- "Weight 0.5 kg"
  weight_unit       VARCHAR(30) NOT NULL DEFAULT 'kg' CHECK ("weight_unit" IN ('g','kg','ml','l','pcs','pack')),
  stock_quantity    INT NOT NULL DEFAULT 0,          -- "Availability: In Stock"
  shipping_info     VARCHAR(255),                    -- "01 day shipping. Free pickup today"
  thumbnail_url     VARCHAR(255),
  status            VARCHAR(30) NOT NULL DEFAULT 'ACTIVE' CHECK ("status" IN ('ACTIVE','HIDDEN','OUT_OF_STOCK')),
  is_featured       BOOLEAN NOT NULL DEFAULT FALSE,  -- section "Featured Product"
  -- Cột tổng hợp (denormalize) để query nhanh cho "Top Rated", "Review Products"
  avg_rating        DECIMAL(2,1) NOT NULL DEFAULT 0,
  review_count      INT NOT NULL DEFAULT 0,
  sold_count        INT NOT NULL DEFAULT 0,
  created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,   -- "Latest Products"
  updated_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_prod_cat FOREIGN KEY (category_id) REFERENCES categories(id),
  CONSTRAINT chk_prod_price CHECK (price >= 0 AND (sale_price IS NULL OR sale_price <= price))                 -- ô SEARCH ở header
);

-- Ảnh lớn + thumbnail slider ở trang Shop Details
CREATE TABLE product_images (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL,
  image_url  VARCHAR(255) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_pimg_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

-- Shop Details > tab "Reviews (1)", "(18 reviews)"
CREATE TABLE product_reviews (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL,
  user_id    BIGINT NOT NULL,
  rating     INTEGER NOT NULL,
  comment    TEXT,
  status     VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK ("status" IN ('PENDING','APPROVED','REJECTED')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rev_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
  CONSTRAINT fk_rev_user FOREIGN KEY (user_id)    REFERENCES users(id)    ON DELETE CASCADE,
  CONSTRAINT chk_rating CHECK (rating BETWEEN 1 AND 5),
  CONSTRAINT uq_review_once UNIQUE (product_id, user_id)
);

-- Icon trái tim trên card sản phẩm
CREATE TABLE wishlists (
  user_id    BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, product_id),
  CONSTRAINT fk_wl_user FOREIGN KEY (user_id)    REFERENCES users(id)    ON DELETE CASCADE,
  CONSTRAINT fk_wl_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 3. CART & ORDER
-- ---------------------------------------------------------------------
CREATE TABLE carts (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL UNIQUE,        -- mỗi user 1 giỏ hàng
  coupon_id  BIGINT NULL,                   -- "Discount Codes > APPLY COUPON"
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE cart_items (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cart_id    BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  quantity   INTEGER NOT NULL DEFAULT 1,
  CONSTRAINT uq_cart_prod UNIQUE (cart_id, product_id),
  CONSTRAINT fk_ci_cart FOREIGN KEY (cart_id)    REFERENCES carts(id)    ON DELETE CASCADE,
  CONSTRAINT fk_ci_prod FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE coupons (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(30) NOT NULL UNIQUE,
  description      VARCHAR(255),
  discount_type    VARCHAR(30) NOT NULL CHECK ("discount_type" IN ('PERCENT','FIXED')),
  discount_value   DECIMAL(12,2) NOT NULL,
  min_order_value  DECIMAL(12,2) NOT NULL DEFAULT 0,
  max_discount     DECIMAL(12,2) NULL,               -- trần giảm khi PERCENT
  usage_limit      INT NULL,                         -- NULL = không giới hạn
  used_count       INT NOT NULL DEFAULT 0,
  starts_at        TIMESTAMP NULL,
  expires_at       TIMESTAMP NULL,
  is_active        BOOLEAN NOT NULL DEFAULT TRUE
);
ALTER TABLE carts ADD CONSTRAINT fk_cart_coupon FOREIGN KEY (coupon_id) REFERENCES coupons(id) ON DELETE SET NULL;

-- Checkout. Thông tin người nhận được SNAPSHOT vào order để sửa/xoá địa chỉ sau này không ảnh hưởng đơn cũ.
CREATE TABLE orders (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code       VARCHAR(20) NOT NULL UNIQUE,      -- ORD-20261018-0001
  user_id          BIGINT NULL,             -- NULL nếu khách guest hoặc user bị xoá
  -- Billing Details
  first_name       VARCHAR(60)  NOT NULL,
  last_name        VARCHAR(60)  NOT NULL,
  email            VARCHAR(150) NOT NULL,
  phone            VARCHAR(20)  NOT NULL,
  -- Shipping address (snapshot)
  ship_country     VARCHAR(60)  NOT NULL,
  ship_address     VARCHAR(255) NOT NULL,
  ship_city        VARCHAR(80)  NOT NULL,
  ship_state       VARCHAR(80),
  ship_postcode    VARCHAR(20),
  order_notes      TEXT,                             -- "Order notes"
  -- Tiền
  subtotal         DECIMAL(12,2) NOT NULL,
  discount_amount  DECIMAL(12,2) NOT NULL DEFAULT 0,
  shipping_fee     DECIMAL(12,2) NOT NULL DEFAULT 0, -- miễn phí nếu subtotal >= free_shipping_threshold
  total            DECIMAL(12,2) NOT NULL,
  coupon_id        BIGINT NULL,
  coupon_code      VARCHAR(30) NULL,                 -- snapshot
  -- Thanh toán ("Check Payment" / "Paypal")
  payment_method   VARCHAR(30) NOT NULL DEFAULT 'COD' CHECK ("payment_method" IN ('COD','BANK_TRANSFER','PAYPAL')),
  payment_status   VARCHAR(30) NOT NULL DEFAULT 'UNPAID' CHECK ("payment_status" IN ('UNPAID','PAID','REFUNDED')),
  transaction_ref  VARCHAR(100) NULL,
  order_status     VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK ("order_status" IN ('PENDING','CONFIRMED','SHIPPING','COMPLETED','CANCELLED')),
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_ord_user   FOREIGN KEY (user_id)   REFERENCES users(id)   ON DELETE SET NULL,
  CONSTRAINT fk_ord_coupon FOREIGN KEY (coupon_id) REFERENCES coupons(id) ON DELETE SET NULL
);

CREATE TABLE order_items (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id     BIGINT NOT NULL,
  product_id   BIGINT NULL,
  product_name VARCHAR(200) NOT NULL,                -- snapshot tên
  unit_price   DECIMAL(12,2) NOT NULL,               -- snapshot giá tại lúc mua
  quantity     INTEGER NOT NULL,
  line_total   DECIMAL(12,2) NOT NULL,
  CONSTRAINT fk_oi_order FOREIGN KEY (order_id)   REFERENCES orders(id)   ON DELETE CASCADE,
  CONSTRAINT fk_oi_prod  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
);

-- Timeline trong trang Order Detail của admin
CREATE TABLE order_status_history (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    BIGINT NOT NULL,
  from_status VARCHAR(20) NULL,
  to_status   VARCHAR(20) NOT NULL,
  note        VARCHAR(255),
  changed_by  BIGINT NULL,
  changed_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_osh_order FOREIGN KEY (order_id)   REFERENCES orders(id) ON DELETE CASCADE,
  CONSTRAINT fk_osh_user  FOREIGN KEY (changed_by) REFERENCES users(id)  ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- 4. BLOG
-- ---------------------------------------------------------------------
CREATE TABLE blog_categories (                       -- "Categories: Beauty (20), Food (5)..."
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  slug VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE blog_tags (                             -- "Search By: Apple, Beauty, Vegetables..."
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50) NOT NULL,
  slug VARCHAR(70) NOT NULL UNIQUE
);

CREATE TABLE blog_posts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id     BIGINT NOT NULL,            -- "By Michael Scofield"
  category_id   INTEGER NOT NULL,
  title         VARCHAR(250) NOT NULL,
  slug          VARCHAR(270) NOT NULL UNIQUE,
  excerpt       VARCHAR(500),
  content       TEXT NOT NULL,
  thumbnail_url VARCHAR(255),
  status        VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK ("status" IN ('DRAFT','PUBLISHED')),
  view_count    INT NOT NULL DEFAULT 0,
  published_at  TIMESTAMP NULL,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_post_author FOREIGN KEY (author_id)   REFERENCES users(id),
  CONSTRAINT fk_post_cat    FOREIGN KEY (category_id) REFERENCES blog_categories(id)
);

CREATE TABLE blog_post_tags (
  post_id BIGINT NOT NULL,
  tag_id  INTEGER NOT NULL,
  PRIMARY KEY (post_id, tag_id),
  CONSTRAINT fk_bpt_post FOREIGN KEY (post_id) REFERENCES blog_posts(id) ON DELETE CASCADE,
  CONSTRAINT fk_bpt_tag  FOREIGN KEY (tag_id)  REFERENCES blog_tags(id)  ON DELETE CASCADE
);

CREATE TABLE blog_comments (                         -- "8 Comments"
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id    BIGINT NOT NULL,
  parent_id  BIGINT NULL,                   -- trả lời comment
  user_id    BIGINT NULL,
  author_name  VARCHAR(100) NOT NULL,
  author_email VARCHAR(150) NOT NULL,
  content    TEXT NOT NULL,
  status     VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK ("status" IN ('PENDING','APPROVED','SPAM')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_bc_post   FOREIGN KEY (post_id)   REFERENCES blog_posts(id)    ON DELETE CASCADE,
  CONSTRAINT fk_bc_parent FOREIGN KEY (parent_id) REFERENCES blog_comments(id) ON DELETE CASCADE,
  CONSTRAINT fk_bc_user   FOREIGN KEY (user_id)   REFERENCES users(id)         ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- 5. CONTENT & SITE
-- ---------------------------------------------------------------------
CREATE TABLE banners (                               -- hero slider "FRUIT FRESH / SHOP NOW", banner sale
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  position   VARCHAR(30) NOT NULL DEFAULT 'HERO' CHECK ("position" IN ('HERO','HOME_SALE','HOME_PROMO')),
  title      VARCHAR(150) NOT NULL,
  subtitle   VARCHAR(255),
  image_url  VARCHAR(255) NOT NULL,
  link_url   VARCHAR(255),
  sort_order INT NOT NULL DEFAULT 0,
  is_active  BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE contact_messages (                      -- Contact > "Leave Message"
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  email      VARCHAR(150) NOT NULL,
  message    TEXT NOT NULL,
  status     VARCHAR(30) NOT NULL DEFAULT 'NEW' CHECK ("status" IN ('NEW','READ','REPLIED')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE newsletter_subscribers (                -- Footer > "Join Our Newsletter Now"
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         VARCHAR(150) NOT NULL UNIQUE,
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  subscribed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Key/value: phone, email, address, open_time, support_time, free_shipping_threshold, shipping_fee...
CREATE TABLE settings (
  setting_key   VARCHAR(60) PRIMARY KEY,
  setting_value VARCHAR(500) NOT NULL,
  description   VARCHAR(150)
);

-- ---------------------------------------------------------------------
-- INDEX (PostgreSQL tạo index bằng câu lệnh riêng)
-- ---------------------------------------------------------------------
CREATE INDEX idx_prod_cat_status   ON products (category_id, status);
CREATE INDEX idx_prod_featured     ON products (is_featured, status);
CREATE INDEX ft_prod_name          ON products USING GIN (to_tsvector('simple', name));   -- tìm kiếm theo tên (ô SEARCH)
CREATE INDEX idx_ord_status_date   ON orders (order_status, created_at);
CREATE INDEX idx_ord_user          ON orders (user_id);
CREATE INDEX idx_post_status_date  ON blog_posts (status, published_at);
